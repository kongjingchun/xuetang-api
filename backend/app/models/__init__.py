def assert_schema_complete() -> None:
    """
    核对已登记表名与计划清单。

    Raises:
        RuntimeError: 漏表或出现计划外的表。
    """
    actual = set(Base.metadata.tables)
    expected = set(EXPECTED_TABLES)
    missing = sorted(expected - actual)
    extra = sorted(actual - expected)
    if missing or extra:
        raise RuntimeError(f"表结构登记不一致，缺失 {missing}，多余 {extra}")


assert_schema_complete()

